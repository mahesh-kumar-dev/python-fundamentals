# my_package/string_utils.py

def shout(text):
    return text.upper()

def whisper(text):
    return text.lower()

def greets(name):
    return f"Hello, {name}"

def is_number(num):
    return num.isdigit()

def is_alphabet(alpha):
    return alpha.isalpha()

def is_uppercase(word):
    return word.isupper()

def is_lowercase(word):
    return word.islower()

